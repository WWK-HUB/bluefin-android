/**
 * Compiles the bundled timbre reference clips into the worker as MP3 base64.
 *
 * Why inline: Fish Audio's API model creation requires prepaid credit
 * ("API model creation limit reached (0/0)" at $0), but ONE-SHOT inline
 * cloning via the TTS `references` field is free with s2.1-pro-free. Embedding
 * the clips lets every device use the built-in voices with zero setup and
 * zero balance. MP3 64kbps keeps each request's overhead ~35KB.
 *
 * Run automatically by `npm run build:pages`. Output: src/builtin-voices.ts
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import lamejs from "@breezystack/lamejs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PACK_DIR = process.env.VOICE_PACK_DIR
  ?? path.join(ROOT, "../app/src/main/assets/voice-packs");

function parseWav(buf) {
  if (buf.toString("ascii", 0, 4) !== "RIFF" || buf.toString("ascii", 8, 12) !== "WAVE") {
    throw new Error("not a RIFF/WAVE file");
  }
  let offset = 12;
  let fmt = null;
  let data = null;
  while (offset + 8 <= buf.length) {
    const id = buf.toString("ascii", offset, offset + 4);
    const size = buf.readUInt32LE(offset + 4);
    if (id === "fmt ") {
      fmt = {
        channels: buf.readUInt16LE(offset + 10),
        sampleRate: buf.readUInt32LE(offset + 12),
        bits: buf.readUInt16LE(offset + 22),
      };
    } else if (id === "data") {
      data = buf.subarray(offset + 8, offset + 8 + size);
    }
    offset += 8 + size + (size % 2);
  }
  if (!fmt || !data) throw new Error("missing fmt/data chunk");
  if (fmt.channels !== 1 || fmt.bits !== 16) throw new Error("expected 16-bit mono");
  return { sampleRate: fmt.sampleRate, samples: new Int16Array(data.buffer, data.byteOffset, data.length / 2) };
}

function encodeMp3(samples, sampleRate) {
  const encoder = new lamejs.Mp3Encoder(1, sampleRate, 64);
  const chunks = [];
  for (let i = 0; i < samples.length; i += 1152) {
    const buf = encoder.encodeBuffer(samples.subarray(i, i + 1152));
    if (buf.length > 0) chunks.push(Buffer.from(buf));
  }
  const end = encoder.flush();
  if (end.length > 0) chunks.push(Buffer.from(end));
  return Buffer.concat(chunks);
}

function resample(samples, fromRate, toRate) {
  if (fromRate === toRate) return samples;
  const ratio = fromRate / toRate;
  const outLen = Math.floor(samples.length / ratio);
  const out = new Int16Array(outLen);
  for (let i = 0; i < outLen; i++) {
    const pos = i * ratio;
    const idx = Math.floor(pos);
    const frac = pos - idx;
    const a = samples[idx] ?? 0;
    const b = samples[idx + 1] ?? a;
    out[i] = Math.round(a + (b - a) * frac);
  }
  return out;
}

const entries = [];
for (const id of ["timbre1", "timbre2"]) {
  const dir = path.join(PACK_DIR, id);
  const manifest = JSON.parse(fs.readFileSync(path.join(dir, "voice.json"), "utf8"));
  const wavBuf = fs.readFileSync(path.join(dir, manifest.reference ?? "reference.wav"));
  const wav = parseWav(wavBuf);
  // Fish accepts MP3 references only at 32/44.1kHz. Resample 24k→44.1k and
  // encode MP3 64kbps: ~26KB vs ~150KB WAV, much cheaper per sentence on
  // mobile networks. Falls back to the original WAV if encoding fails.
  let audioBuf = wavBuf;
  let kind = "wav";
  try {
    const resampled = resample(wav.samples, wav.sampleRate, 44100);
    const mp3 = encodeMp3(resampled, 44100);
    if (mp3.length > 1000) {
      audioBuf = mp3;
      kind = "mp3@44.1k";
    }
  } catch (e) {
    console.log(`${id}: mp3 encode failed (${e.message}), keeping WAV`);
  }
  console.log(`${id}: ${(wav.samples.length / wav.sampleRate).toFixed(1)}s → ${(audioBuf.length / 1024).toFixed(1)} KB ${kind}`);
  entries.push(`  ${id}: {\n    audioB64: "${audioBuf.toString("base64")}",\n    text: ${JSON.stringify(manifest.referenceText ?? "")},\n  },`);
}

const out = `/** GENERATED by scripts/build-builtin-voices.mjs — do not edit by hand. */
export interface BuiltinVoice {
  audioB64: string;
  text: string;
}

export const BUILTIN_VOICES: Record<string, BuiltinVoice> = {
${entries.join("\n")}
};
`;
fs.writeFileSync(path.join(ROOT, "src/builtin-voices.ts"), out);
console.log("src/builtin-voices.ts written");